#!/usr/bin/env node
/*
 * Optional: packs the PD weekly Balance Scorecard template (.pptx) into data/ppt-template.js so a local copy of the
 * site can export the weekly PowerPoint without loading the template first. The output contains internal programme
 * data and is git-ignored (this repository is public).
 *
 *   node tools/build-ppt-template.js "EAST - Program - Balance Scorecard - KPI.pptx"
 */
const fs = require("fs"), path = require("path");
const src = process.argv[2];
if (!src) { console.error("Usage: node tools/build-ppt-template.js <template.pptx>"); process.exit(1); }
const out = path.join(__dirname, "..", "data", "ppt-template.js");
fs.writeFileSync(out, "/* Generated by tools/build-ppt-template.js — internal, not committed. */\nwindow.SAR_PPT_TEMPLATE = " +
  JSON.stringify({ name: path.basename(src), builtAt: new Date().toISOString(), b64: fs.readFileSync(src).toString("base64") }) + ";\n");
console.log("Wrote " + out + " (" + Math.round(fs.statSync(out).size / 1024) + " KB)");
