#!/usr/bin/env node
/*
 * Builds assets/js/publish-kit.js — the site's own code (HTML shell, CSS, scripts, logos) packed into
 * one JS file. The Publish button loads it and combines it with the current data to produce a single,
 * self-contained weekly-report HTML file. Contains no project data.
 *
 * Run after changing any file in index.html, assets/css or assets/js:
 *   node tools/build-publish-kit.js
 */
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

// Scripts a published report needs, in load order (no Excel import libraries).
const SCRIPTS = [
  "assets/vendor/chart.umd.min.js",
  "assets/vendor/chartjs-plugin-datalabels.min.js",
  "assets/js/importer.js",
  "assets/js/store.js",
  "assets/js/ui.js",
  "assets/js/pages.js",
  "assets/js/xlcalc.js",     // formula engine of the team update page
  "assets/js/cardform.js",   // also the code of the team update page (Card Updates)
  "assets/js/print.js",
  "assets/js/app.js"   // publish.js is left out: a published report cannot publish again
];
const IMAGES = ["assets/img/sar-logo.png", "assets/img/sar-vision2030.png"];

const kit = {
  builtAt: new Date().toISOString(),
  html: read("index.html"),
  css: read("assets/css/styles.css"),
  scripts: SCRIPTS.map((p) => ({ name: p, code: read(p) })),
  images: Object.fromEntries(IMAGES.map((p) => [p, "data:image/png;base64," + fs.readFileSync(path.join(root, p)).toString("base64")]))
};
const out = path.join(root, "assets/js/publish-kit.js");
fs.writeFileSync(out, "/* Generated by tools/build-publish-kit.js — do not edit. */\nwindow.SAR_PUBLISH_KIT = " + JSON.stringify(kit) + ";\n");
console.log("Wrote " + out + " (" + (fs.statSync(out).size / 1024).toFixed(0) + " KB)");
